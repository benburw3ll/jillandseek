// Refreshes src/towns-data.ts, the local table of Minnesota cities and towns with approximate
// coordinates, from the US Census Bureau's Gazetteer places file (public domain).
//
//   node packages/core/scripts/refresh-towns.mjs [<gazetteer file>]
//
// With no argument it downloads Minnesota's places file (state 27) from the Census Bureau, once.
// The app itself never makes this request: the table is generated here and committed.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const YEAR = 2024
const URL_ = `https://www2.census.gov/geo/docs/maps-data/data/gazetteer/${YEAR}_Gazetteer/${YEAR}_gaz_place_27.txt`
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'towns-data.ts')

/** The place kinds the Gazetteer appends to a name (Minnesota uses these two). */
const SUFFIX = / (city|CDP)$/

async function readSource(path) {
  if (path !== undefined) return readFileSync(path, 'utf8')
  const res = await fetch(URL_, {
    headers: { 'user-agent': 'JillAndSeek-towns-refresh (+https://github.com/benburw3ll/jillandseek)' },
  })
  if (!res.ok) throw new Error(`the Census Bureau answered ${res.status}`)
  return res.text()
}

const text = await readSource(process.argv[2])
const [header, ...rows] = text.split(/\r?\n/).filter((l) => l.trim() !== '')
const cols = header.split('\t').map((c) => c.trim())
const at = (name) => {
  const i = cols.indexOf(name)
  if (i < 0) throw new Error(`the file has no ${name} column`)
  return i
}
const [usps, name, lat, lon] = [at('USPS'), at('NAME'), at('INTPTLAT'), at('INTPTLONG')]

const towns = new Map()
for (const row of rows) {
  const f = row.split('\t').map((c) => c.trim())
  if (f[usps] !== 'MN') continue
  const town = f[name].replace(SUFFIX, '')
  // A city and a CDP can share a name; the file lists cities first, so the city is kept.
  if (towns.has(town.toLowerCase())) continue
  towns.set(town.toLowerCase(), [town, Number(Number(f[lat]).toFixed(3)), Number(Number(f[lon]).toFixed(3))])
}
const sorted = [...towns.values()].sort((a, b) => a[0].localeCompare(b[0], 'en'))
if (sorted.length < 500) throw new Error(`only ${sorted.length} towns: the file is not the one expected`)

const lines = [
  `// Generated by packages/core/scripts/refresh-towns.mjs from the US Census Bureau's ${YEAR} Gazetteer`,
  '// places file for Minnesota (public domain). Do not edit by hand: run the script.',
  '// Each row is [name, latitude, longitude], the place’s internal point to three decimals.',
  'export const TOWN_ROWS: readonly (readonly [string, number, number])[] = [',
  // Quoted the way the formatter wants (single quotes unless the name holds one).
  ...sorted.map(([t, la, lo]) => `  [${t.includes("'") ? JSON.stringify(t) : `'${t}'`}, ${la}, ${lo}],`),
  ']',
  '',
]
writeFileSync(OUT, lines.join('\n'))
console.log(`towns: ${sorted.length}`)
